def env_bool(name, default=False):
    value = os.environ.get(name, str(default)).strip().lower()
    if value in ('1', 'true', 'yes', 'on'):
        return True
    if value in ('0', 'false', 'no', 'off'):
        return False
    raise ImproperlyConfigured(f'{name} must be true or false')


